def _row_height(row, widths):
    """Estimate a wrapped row height (pt) from the longest cell vs column width."""
    lines = 1
    for i, v in enumerate(row, start=1):
        w = widths.get(get_column_letter(i), 20)
        per_line = max(6, int(w) - 1)
        for part in str(v if v is not None else "").split("\n"):
            lines = max(lines, -(-len(part) // per_line))
    return min(175, max(34, 15 * lines))


def build_custom(wb, name, title, headers, widths, rows):
    """Generic sheet: title row, header row, then free-form rows (wrap text)."""
    ws = wb.create_sheet(name)
    last_col = len(headers)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=last_col)
    t = ws.cell(row=1, column=1, value=title)
    t.font = Font(name=THAI_FONT, size=13, bold=True, color="FFFFFF")
    t.fill = TITLE_FILL
    t.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[1].height = 30
    for i, h in enumerate(headers, start=1):
        c = ws.cell(row=2, column=i, value=h)
        c.font = Font(name=THAI_FONT, size=11, bold=True, color="FFFFFF")
        c.fill = HEADER_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
    ws.row_dimensions[2].height = 26
    for r, row in enumerate(rows, start=3):
        for i, v in enumerate(row, start=1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = Font(name=THAI_FONT, size=10, bold=(i == 1))
            c.alignment = Alignment(horizontal="left", vertical="top", wrap_text=True)
            c.border = BORDER
            if r % 2 == 0:
                c.fill = ZEBRA
        ws.row_dimensions[r].height = _row_height(row, widths)
    for col, w in widths.items():
        ws.column_dimensions[col].width = w
    ws.freeze_panes = "A3"
    return len(rows)


