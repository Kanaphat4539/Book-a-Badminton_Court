def style_range(ws, row, cols, *, fill=None, font=None, align=None, border=True):
    for c in range(1, cols + 1):
        cell = ws.cell(row=row, column=c)
        if fill:
            cell.fill = fill
        if font:
            cell.font = font
        if align:
            cell.alignment = align
        if border:
            cell.border = BORDER


def build_tc_sheet(wb, name, title, cases):
    ws = wb.create_sheet(name)
    n = len(cases)
    last_col = 7
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=last_col)
    t = ws.cell(row=1, column=1, value=title)
    t.font = Font(name=THAI_FONT, size=13, bold=True, color="FFFFFF")
    t.fill = TITLE_FILL
    t.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[1].height = 30

    for i, h in enumerate(HEADERS, start=1):
        c = ws.cell(row=2, column=i, value=h)
        c.font = Font(name=THAI_FONT, size=11, bold=True, color="FFFFFF")
        c.fill = HEADER_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
    ws.row_dimensions[2].height = 26

    for r, case in enumerate(cases, start=3):
        tc_id, scenario, steps, data, expected = case
        values = [tc_id, scenario, steps, data, expected, "", "รอทดสอบ"]
        for i, v in enumerate(values, start=1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = Font(name=THAI_FONT, size=10)
            if i in (3, 4, 5, 6):
                c.alignment = Alignment(horizontal="left", vertical="top", wrap_text=True)
            elif i == 1:
                c.alignment = Alignment(horizontal="left", vertical="top")
            elif i == 2:
                c.alignment = Alignment(horizontal="left", vertical="top", wrap_text=True)
            else:
                c.alignment = Alignment(horizontal="center", vertical="top")
            c.border = BORDER
            if r % 2 == 0:
                c.fill = ZEBRA
        ws.row_dimensions[r].height = _row_height(values, WIDTHS)
    ws.cell(row=3, column=1).font = Font(name=THAI_FONT, size=10, bold=True)

    for col, w in WIDTHS.items():
        ws.column_dimensions[col].width = w
    ws.freeze_panes = "A3"
    ws.auto_filter.ref = f"A2:G{2 + n}"

    dv = DataValidation(type="list", formula1=STATUS_LIST, allow_blank=True,
                        showDropDown=False)
    dv.error = "เลือกค่า: ผ่าน / ไม่ผ่าน / รอทดสอบ / ตรวจไม่ได้"
    dv.errorTitle = "ค่า Status ไม่ถูกต้อง"
    ws.add_data_validation(dv)
    dv.add(f"G3:G{2 + n}")
    return n


