def _coverage_cell(covered):
    return "; ".join(f"{tid} → {tc}" for tid, tc in covered.items()) or "—"


def _build_mapping_rows():
    rows = []
    for sheet, section, tids, covered, missing, note, kind in MAPPING_GROUPS:
        if kind == "req":
            if missing:
                tail = f"ยังไม่มีเคส: {', '.join(missing)} ({len(missing)} รายการ) — {note}"
            else:
                tail = f"ครบทั้งหมด: มี Test Case ครอบทุก ID ในหมวดนี้แล้ว ({len(covered)} รายการ) — {note}"
            rows.append((sheet, section, tids, _coverage_cell(covered), tail))
        else:
            rows.append((sheet, section, tids, "—", f"ไม่สร้างชีต Test Case: {note}"))
    return rows


